"use client";

import type { SourceCitation } from "./types";

/* ───────────────────────────────────────────
   Unified report export module.

   Every export surface (in-chat report generator, saved report viewer,
   follow-up actions) routes through exportReport(). Formatting, metadata
   headers, citation appendices, filenames, and the print/PDF path are all
   defined here exactly once.
   ─────────────────────────────────────────── */

export type ExportFormat = "pdf" | "markdown" | "html" | "json";

export interface ExportReportDocument {
  title: string;
  markdown: string;
  sources?: SourceCitation[];
  metadata?: Record<string, unknown>;
}

export interface ExportHtmlOptions {
  cover?: boolean;
  toc?: boolean;
}

export const EXPORT_GENERATOR = "ResearchSwarm AI";

export function reportFilename(title: string): string {
  const slug = title
    .replace(/[^\w\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-")
    .toLowerCase();
  return slug || "research-report";
}

function formatDate(): string {
  return new Date().toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}

function markdownLinks(sources: SourceCitation[]): string {
  return sources
    .map((source, i) => `${i + 1}. [${source.title}](${source.url || "#"})`)
    .join("\n");
}

/* ── Markdown ────────────────────────────── */

export function buildReportMarkdown(doc: ExportReportDocument): string {
  const parts: string[] = [];
  parts.push(`# ${doc.title}`);
  parts.push("");
  parts.push(`> **Date:** ${formatDate()}`);
  parts.push(`> **Generated by:** ${EXPORT_GENERATOR}`);
  if (doc.sources && doc.sources.length > 0) {
    parts.push(`> **Sources cited:** ${doc.sources.length}`);
  }
  parts.push("");
  parts.push(doc.markdown.trim());
  if (doc.sources && doc.sources.length > 0) {
    parts.push("");
    parts.push("## Sources");
    parts.push("");
    parts.push(markdownLinks(doc.sources));
  }
  return parts.join("\n");
}

/* ── HTML ────────────────────────────────── */

function extractSections(md: string): { heading: string; content: string }[] {
  const sections: { heading: string; content: string }[] = [];
  const lines = md.split("\n");
  let current: { heading: string; content: string[] } | null = null;
  for (const line of lines) {
    const headingMatch = line.match(/^#{1,3}\s+(.+)/);
    if (headingMatch) {
      if (current) {
        sections.push({
          heading: current.heading,
          content: current.content.join("\n").trim(),
        });
      }
      current = { heading: headingMatch[1], content: [] };
    } else if (current) {
      current.content.push(line);
    }
  }
  if (current) {
    sections.push({
      heading: current.heading,
      content: current.content.join("\n").trim(),
    });
  }
  return sections;
}

function escapeHtml(unsafe: string): string {
  return unsafe
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function coverPage(title: string): string {
  return [
    `<div style="page-break-after:always;text-align:center;padding-top:120px;">`,
    `<h1 style="font-size:2.5em;margin-bottom:8px;background:linear-gradient(135deg,#6366f1,#06b6d4);-webkit-background-clip:text;-webkit-text-fill-color:transparent;background-clip:text;">${escapeHtml(title)}</h1>`,
    `<p style="font-size:1.1em;color:#64748b;margin-bottom:40px;">Research Report</p>`,
    `<hr style="width:80px;margin:0 auto 32px;border:none;height:2px;background:linear-gradient(90deg,#6366f1,#06b6d4);"/>`,
    `<p style="color:#94a3b8;font-size:0.85em;">Generated by ${EXPORT_GENERATOR}</p>`,
    `<p style="color:#94a3b8;font-size:0.85em;">${formatDate()}</p>`,
    `</div>`,
  ].join("\n");
}

function tableOfContents(sections: { heading: string; content: string }[]): string {
  if (sections.length === 0) return "";
  const items = sections
    .map(
      (s, i) =>
        `<li style="margin:4px 0;"><a href="#section-${i}" style="color:#8b5cf6;text-decoration:none;">${escapeHtml(s.heading)}</a></li>`,
    )
    .join("\n");
  return [
    `<div style="page-break-after:always;">`,
    `<h2 style="font-size:1.6em;margin-bottom:16px;">Table of Contents</h2>`,
    `<ol style="list-style:none;padding:0;">${items}</ol>`,
    `</div>`,
  ].join("\n");
}

function markdownToHtml(md: string): string {
  const esc = escapeHtml;
  return md
    .split("\n")
    .map((line) => {
      if (line.startsWith("# ")) {
        return `<h1 id="${esc(line.slice(2).toLowerCase().replace(/\s+/g, "-"))}">${esc(line.slice(2))}</h1>`;
      }
      if (line.startsWith("## ")) {
        return `<h2 id="${esc(line.slice(3).toLowerCase().replace(/\s+/g, "-"))}">${esc(line.slice(3))}</h2>`;
      }
      if (line.startsWith("### ")) return `<h3>${esc(line.slice(4))}</h3>`;
      if (line.startsWith("> **")) {
        return `<blockquote style="border-left:3px solid #8b5cf6;padding-left:12px;margin:8px 0;color:#64748b;">${esc(line.slice(2))}</blockquote>`;
      }
      if (line.startsWith("> ")) {
        return `<blockquote style="border-left:3px solid #8b5cf6;padding-left:12px;margin:8px 0;color:#64748b;">${esc(line.slice(2))}</blockquote>`;
      }
      if (line.startsWith("- **") && line.includes("** —")) {
        return `<li style="margin:4px 0;"><strong>${esc(line.slice(4).split("** —")[0])}</strong> — ${esc(line.split("** —")[1])}</li>`;
      }
      if (line.startsWith("- ")) return `<li style="margin:4px 0;">${esc(line.slice(2))}</li>`;
      if (line.match(/^\d+\.\s/)) return `<li style="margin:4px 0;">${esc(line.replace(/^\d+\.\s/, ""))}</li>`;
      if (line.startsWith("---")) return `<hr style="margin:24px 0;border:none;border-top:1px solid #e2e8f0;" />`;
      if (line === "") return "<br/>";
      return `<p style="line-height:1.7;margin:8px 0;">${esc(line)}</p>`;
    })
    .join("\n");
}

export function buildReportHTML(
  doc: ExportReportDocument,
  options: ExportHtmlOptions = {},
): string {
  const sections = extractSections(doc.markdown);
  const bodyParts: string[] = [];

  if (options.cover !== false) bodyParts.push(coverPage(doc.title));
  if (options.toc !== false && sections.length > 0) {
    bodyParts.push(tableOfContents(sections));
  }
  bodyParts.push(
    `<div style="max-width:800px;margin:0 auto;padding:20px;">${markdownToHtml(doc.markdown)}</div>`,
  );

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Research Report: ${escapeHtml(doc.title)}</title>
  <style>
    @page { margin: 20mm; }
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; max-width: 800px; margin: 0 auto; padding: 20px; line-height: 1.6; color: #1a1a2e; background: #fff; }
    h1 { font-size: 2em; border-bottom: 2px solid #e2e8f0; padding-bottom: 8px; margin-top: 32px; }
    h2 { font-size: 1.4em; margin-top: 28px; color: #1e293b; }
    h3 { font-size: 1.15em; margin-top: 20px; color: #334155; }
    a { color: #8b5cf6; }
    @media print { body { padding: 0; } }
  </style>
</head>
<body>${bodyParts.join("\n")}</body>
</html>`;
}

/* ── JSON ────────────────────────────────── */

export function buildReportJSON(doc: ExportReportDocument): string {
  return JSON.stringify(
    {
      title: doc.title,
      generated_by: EXPORT_GENERATOR,
      generated_at: new Date().toISOString(),
      sources: doc.sources ?? [],
      markdown: buildReportMarkdown(doc),
      metadata: doc.metadata ?? {},
    },
    null,
    2,
  );
}

/* ── Delivery ────────────────────────────── */

function downloadText(content: string, filename: string, mime: string): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  anchor.click();
  URL.revokeObjectURL(url);
}

function openPrintWindow(html: string): void {
  const blob = new Blob([html], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  const win = window.open(url, "_blank");
  if (win) {
    win.focus();
    setTimeout(() => win.print(), 500);
  } else {
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = "report.html";
    anchor.click();
  }
  setTimeout(() => URL.revokeObjectURL(url), 60000);
}

export function exportReport(
  doc: ExportReportDocument,
  format: ExportFormat,
  options?: ExportHtmlOptions,
): void {
  const base = reportFilename(doc.title);
  switch (format) {
    case "markdown":
      downloadText(buildReportMarkdown(doc), `${base}.md`, "text/markdown;charset=utf-8");
      break;
    case "html":
      downloadText(buildReportHTML(doc, options), `${base}.html`, "text/html;charset=utf-8");
      break;
    case "json":
      downloadText(buildReportJSON(doc), `${base}.json`, "application/json;charset=utf-8");
      break;
    case "pdf":
      openPrintWindow(buildReportHTML(doc, options));
      break;
  }
}
